// Library-level interface entries only cover public members, but a
// module carrying the whole framework reaches private platform members too
// (dart:ui's _RRectLike._offsetBy is the one that showed up first). Emit
// explicit entries for every private class and private member of the platform
// libraries, to be appended to the library-level dart:* interface.
//
// Usage: gen-platform-privates --platform <platform.dill> --out <out.yaml>

import 'dart:io';

import 'package:kernel/kernel.dart';

const List<String> _libs = <String>[
  'dart:core',
  'dart:async',
  'dart:collection',
  'dart:convert',
  'dart:io',
  'dart:math',
  'dart:typed_data',
  'dart:isolate',
  'dart:developer',
  'dart:ffi',
  'dart:_internal',
  'dart:ui',
];

String _key(Member m) {
  if (m is Procedure) {
    if (m.isGetter) return 'get:${m.name.text}';
    if (m.isSetter) return 'set:${m.name.text}';
  }
  return m.name.text;
}

String _q(String s) => "'${s.replaceAll("'", "''")}'";

void main(List<String> args) {
  if (args.length != 4 || args[0] != '--platform' || args[2] != '--out') {
    stderr.writeln(
        'usage: gen_platform_privates.dart --platform <platform.dill> --out <out.yaml>');
    exitCode = 64;
    return;
  }
  final component = loadComponentFromBinary(args[1]);
  final privateClasses = <String, Set<String>>{};
  final privateMembers = <String, Map<String, Set<String>>>{};
  final overridable = <String, Map<String, Set<String>>>{};

  for (final lib in component.libraries) {
    final uri = lib.importUri.toString();
    if (!_libs.contains(uri)) continue;

    void addMember(String container, Member m) {
      // LibraryIndex only indexes a private name inside its own library, so an
      // entry for a member private to a different library can never resolve.
      if (m.name.isPrivate && m.name.library != lib) return;
      privateMembers
          .putIfAbsent(uri, () => {})
          .putIfAbsent(container, () => {})
          .add(_key(m));
      if (m.isInstanceMember) {
        overridable
            .putIfAbsent(uri, () => {})
            .putIfAbsent(container, () => {})
            .add(_key(m));
      }
    }

    for (final m in lib.members) {
      if (m.name.text.startsWith('_')) addMember('::', m);
    }
    for (final cls in lib.classes) {
      final isPrivateClass = cls.name.startsWith('_');
      if (isPrivateClass) {
        privateClasses.putIfAbsent(uri, () => {}).add(cls.name);
      }
      for (final m in cls.members) {
        // A private class needs all of its members named; a public class needs
        // only the private ones, since the library-level entry covers the rest.
        if (isPrivateClass || m.name.text.startsWith('_')) {
          addMember(cls.name, m);
        }
      }
    }
  }

  final buf = StringBuffer()
    ..writeln('# Generated by gen_platform_privates.dart -- do not edit.')
    ..writeln(
        '# Private platform declarations, which library-level entries skip.');

  void emitClasses(String section) {
    buf.writeln('$section:');
    for (final lib in privateClasses.keys.toList()..sort()) {
      final names = privateClasses[lib]!.toList()..sort();
      buf.writeln('  - library: ${_q(lib)}');
      buf.writeln('    class: [${names.map(_q).join(', ')}]');
    }
    buf.writeln();
  }

  void emitMembers(String section, Map<String, Map<String, Set<String>>> src) {
    buf.writeln('$section:');
    for (final lib in src.keys.toList()..sort()) {
      for (final container in src[lib]!.keys.toList()..sort()) {
        for (final mem in src[lib]![container]!.toList()..sort()) {
          buf.writeln('  - library: ${_q(lib)}');
          if (container != '::') buf.writeln('    class: ${_q(container)}');
          buf.writeln('    member: ${_q(mem)}');
        }
      }
    }
    buf.writeln();
  }

  emitClasses('can-be-used-as-type');
  emitMembers('callable', privateMembers);
  emitMembers('can-be-overridden', overridable);

  File(args[3]).writeAsStringSync(buf.toString());

  var pc = 0;
  privateClasses.forEach((_, s) => pc += s.length);
  var pm = 0;
  privateMembers.forEach((_, cs) => cs.forEach((_, s) => pm += s.length));
  stdout.writeln('private classes : $pc');
  stdout.writeln('private members : $pm');
  stdout.writeln('wrote ${args[3]}');
}
